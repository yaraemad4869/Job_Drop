using JobDrop.Application.Contracts.Persistence;
using JobDrop.Application.Features.Drops.Commands;
using JobDrop.Domain.Enums;
using JobDrop.Domain.Exceptions;
using JobDrop.Domain.Services;
using Microsoft.EntityFrameworkCore;
using MediatR;

// Namespace alias to resolve conflict: JobDrop.Application (namespace) vs Application (entity)
using AppEntity = global::JobDrop.Domain.Entities.Drops.Application;
using DropEntity = global::JobDrop.Domain.Entities.Drops.DropLedgerEntry;

namespace JobDrop.Application.Features.Drops.Handlers;

/// <summary>
/// Dispatches a drop atomically.
/// 1. Checks Idempotency.
/// 2. Validates JobDailyIntake capacity.
/// 3. Consumes wallet credit atomically via DropWalletPolicy.
/// 4. Creates Application and DropLedgerEntry.
/// </summary>
public sealed class DispatchDropCommandHandler : IRequestHandler<DispatchDropCommand, DispatchDropResult>
{
    private readonly IApplicationDbContext _context;
    private readonly DropWalletPolicy _walletPolicy;

    public DispatchDropCommandHandler(IApplicationDbContext context, DropWalletPolicy walletPolicy)
    {
        _context = context;
        _walletPolicy = walletPolicy;
    }

    public async Task<DispatchDropResult> Handle(DispatchDropCommand request, CancellationToken cancellationToken)
    {
        // 1. Idempotency Check
        var existingApplication = await _context.Applications
            .FirstOrDefaultAsync(a => a.IdempotencyKey == request.IdempotencyKey, cancellationToken);

        if (existingApplication != null)
        {
            // Return existing result (idempotent response)
            return new DispatchDropResult(
                existingApplication.Id,
                WalletBucket.Daily, // Fallback
                DateTime.UtcNow.AddHours(48),
                1
            );
        }

        // 2. Validate Job and Daily Intake Capacity
        var job = await _context.Jobs
            .FirstOrDefaultAsync(j => j.Id == request.JobId, cancellationToken)
            ?? throw new DomainRuleException("Job not found");

        var today = DateOnly.FromDateTime(DateTime.UtcNow);
        var intake = await _context.JobDailyIntakes
            .FirstOrDefaultAsync(i => i.JobId == request.JobId && i.MarketDate == today, cancellationToken);

        if (intake == null || intake.DeliveredCount >= job.DailyIntakeCap)
        {
            throw new DomainRuleException("Job daily intake capacity exceeded");
        }

        // 3. Get Wallet and Consume Credit Atomically
        var wallet = await _context.DropWalletBalances
            .FirstOrDefaultAsync(w => w.CandidateProfileId == request.CandidateProfileId, cancellationToken)
            ?? throw new DomainRuleException("Candidate wallet not found");

        var consumedBucket = _walletPolicy.ConsumeCredit(wallet);

        // 4. Create Entities using factory method
        var applicationId = Guid.NewGuid();

        // Use factory method to create Application with Id
        var application = AppEntity.Create(
            id: applicationId,
            jobId: request.JobId,
            companyId: job.CompanyId,
            candidateProfileId: request.CandidateProfileId,
            idempotencyKey: request.IdempotencyKey
        );

        application.Status = DropStatus.Delivered;
        application.DeliveredAtUtc = DateTimeOffset.UtcNow;

        var ledgerEntry = new DropEntity(
            candidateProfileId: request.CandidateProfileId,
            bucket: consumedBucket,
            delta: -1,
            reasonCode: "dispatch_drop",
            referenceId: applicationId.ToString(),
            idempotencyKey: $"dispatch_{request.IdempotencyKey}"
        );

        // 5. Atomic Save
        _context.Applications.Add(application);

        // Create immutable ApplicationSnapshot using object initializer
        var snapshot = new global::JobDrop.Domain.Entities.Drops.ApplicationSnapshot
        {
            ApplicationId = application.Id,
            ResumeDocumentId = null,  // TODO: from request.ResumeDocumentId
            ResumeVersion = 1,
            RedactedResumeKey = null, // Generated by DocumentScanWorker
            ProfileSnapshotJson = "{}",
            MatchBreakdownJson = "{}",
            MatchScore = 0m,
            ConsentVersion = "1.0",
            SharingProtocolJson = "{}",
            FrozenAtUtc = DateTimeOffset.UtcNow
        };
        _context.ApplicationSnapshots.Add(snapshot);
        _context.DropLedgerEntries.Add(ledgerEntry);
        intake.IncrementDelivered();

        await _context.SaveChangesAsync(cancellationToken);

        // 6. Return result (4 parameters as per DispatchDropResult signature)
        return new DispatchDropResult(
            ApplicationId: application.Id,
            ConsumedFrom: consumedBucket,
            DueAtUtc: DateTime.UtcNow.AddHours(48),
            BatchRank: 1
        );
    }
}
